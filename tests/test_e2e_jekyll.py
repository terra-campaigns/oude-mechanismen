#!/usr/bin/env python3
"""End-to-end Jekyll fixture-vault build tests (GitHub issue #34).

Builds a minimal campaign vault in a temporary directory, installs the
oude-mechanismen gem from the local repository checkout via a path Gemfile,
and runs a real ``bundle exec jekyll build``.

Post-removal scope (issues #25/#35, PR #72): the engine no longer ships
``jekyll/all-content.md`` or ``jekyll/_plugins/llm_content.rb``. These tests
verify that:

1. A default fixture vault builds cleanly with the gem's in-memory plugin
   and includes, emits ``.agents/context/catalog.json`` with Tier 1 entries,
   and does NOT emit ``_site/all-content.html``.
2. A vault that supplies its own root ``all-content.md`` override still
   builds cleanly and renders that page as a normal page — the retired
   ``Jekyll::LlmContentGenerator`` is gone, so there is nothing left to
   conflict with or yield to.

Skipped automatically when ``ruby``/``bundle`` are unavailable on the host.
All test assertions and docstrings strictly adhere to British English.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

RUBY_AVAILABLE = shutil.which("ruby") is not None and shutil.which("bundle") is not None


def _write_fixture_vault(vault: Path) -> None:
    """Scaffold a minimal Jekyll vault wired to the local engine checkout."""
    (vault / "campaigns").mkdir(parents=True)
    (vault / ".agents" / "context").mkdir(parents=True)
    (vault / "_config.yml").write_text(
        "\n".join(
            [
                'title: "Fixture Vault"',
                "plugins:",
                "  - oude-mechanismen",
                "exclude:",
                '  - ".agents"',
                '  - "Gemfile"',
                '  - "Gemfile.lock"',
                '  - "vendor"',
                '  - ".bundle"',
                "",
            ]
        ),
        encoding="utf-8",
    )
    (vault / "index.md").write_text(
        "---\ntitle: Home\n---\n\n# Fixture Home\n\nWelcome to the fixture vault.\n",
        encoding="utf-8",
    )
    (vault / "campaigns" / "session-001.md").write_text(
        "---\ntitle: Session 001\ntype: session\n---\n\n# Session 001\n\nThe party entered the mill.\n",
        encoding="utf-8",
    )
    gemfile = (
        'source "https://rubygems.org"\n'
        'gem "jekyll", "~> 4.4"\n'
        f'gem "oude-mechanismen", path: {json.dumps(str(REPO_ROOT))}\n'
    )
    (vault / "Gemfile").write_text(gemfile, encoding="utf-8")


def _run(cmd, cwd: Path, env_extra: dict, timeout: int = 600) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    env.update(env_extra)
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)


@unittest.skipUnless(RUBY_AVAILABLE, "ruby and bundle executables not found on host system")
class TestE2EJekyllBuild(unittest.TestCase):
    """Real ``bundle exec jekyll build`` against a fixture vault (issue #34)."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp(prefix="oude-e2e-jekyll-"))
        cls.vault = cls.tmp / "vault"
        cls.vault.mkdir()
        _write_fixture_vault(cls.vault)
        cls.bundle_env = {
            "BUNDLE_PATH": str(cls.vault / "vendor" / "bundle"),
            "BUNDLE_APP_CONFIG": str(cls.vault / ".bundle"),
        }
        install = _run(["bundle", "install", "--quiet"], cwd=cls.vault, env_extra=cls.bundle_env)
        if install.returncode != 0:
            shutil.rmtree(cls.tmp, ignore_errors=True)
            raise unittest.SkipTest(
                f"bundle install unavailable (offline?): {install.stderr[-400:]}"
            )
        cls.build = _run(["bundle", "exec", "jekyll", "build"], cwd=cls.vault, env_extra=cls.bundle_env)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def test_1_build_succeeds_and_pages_render(self):
        """Verify the fixture vault builds and its pages render into _site/."""
        self.assertEqual(self.build.returncode, 0, self.build.stderr[-2000:])
        self.assertTrue((self.vault / "_site" / "index.html").is_file())
        self.assertTrue((self.vault / "_site" / "campaigns" / "session-001.html").is_file())

    def test_2_catalog_json_emitted_with_tier1_entries(self):
        """Verify the gem plugin writes .agents/context/catalog.json during the build."""
        self.assertEqual(self.build.returncode, 0, self.build.stderr[-2000:])
        catalog_path = self.vault / ".agents" / "context" / "catalog.json"
        self.assertTrue(catalog_path.is_file(), "catalog.json not generated by data_extractor")
        catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
        self.assertEqual(catalog["tier"], 1)
        self.assertGreaterEqual(catalog["total_entries"], 1)
        paths = [entry["path"] for entry in catalog["entries"]]
        self.assertIn("campaigns/session-001.md", paths)

    def test_3_monolithic_all_content_html_not_generated(self):
        """Regression guard for #25/#35: no /all-content.html unless the vault ships its own."""
        self.assertEqual(self.build.returncode, 0, self.build.stderr[-2000:])
        self.assertFalse(
            (self.vault / "_site" / "all-content.html").exists(),
            "retired monolithic LLM dump must not be synthesised by the engine",
        )

    def test_4_vault_supplied_all_content_override_builds_as_normal_page(self):
        """Verify a vault's own root all-content.md builds cleanly (no engine generator conflict)."""
        override = self.vault / "all-content.md"
        override.write_text(
            "---\ntitle: Custom dump\n---\n\nCustom vault-supplied dump.\n",
            encoding="utf-8",
        )
        try:
            result = _run(
                ["bundle", "exec", "jekyll", "build"],
                cwd=self.vault,
                env_extra=self.bundle_env,
                timeout=300,
            )
            self.assertEqual(result.returncode, 0, result.stderr[-2000:])
            self.assertTrue(
                (self.vault / "_site" / "all-content.html").is_file(),
                "vault-supplied all-content.md must render as an ordinary page",
            )
        finally:
            override.unlink(missing_ok=True)


if __name__ == "__main__":
    unittest.main()
